// Build both pages and embed them into convex/lib/assets.ts.
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

for (const entry of ["index", "think"]) {
  execSync("npx vite build --logLevel warn", { stdio: "inherit", env: { ...process.env, GO_ENTRY: entry } });
}
const app = readFileSync("web/dist/index/index.html", "utf8");
const think = readFileSync("web/dist/think/think.html", "utf8");
writeFileSync(
  "convex/lib/assets.ts",
  `// Generated by scripts/build-web.mjs. Do not edit.\nexport const APP_HTML = ${JSON.stringify(app)};\nexport const THINK_HTML = ${JSON.stringify(think)};\n`,
);
console.log(`app ${(app.length / 1024).toFixed(0)} KB, think ${(think.length / 1024).toFixed(0)} KB -> convex/lib/assets.ts`);
